/// Why a call failed. A failed call changes no state.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum VaultError {
    AccountNotSpeakable,
    AlreadyExists,
    NoVault,
    InsufficientDeposit,
    ZeroDeposit,
    ContactExists,
    BadContact,
    ContactNotFound,
    TooManyContacts,
    SoundsLikeContact,
    InvalidLimits,
    NoLimitsChange,
    BadNonce,
    BadReceiver,
    AmountNotSpeakable,
    OverTransferLimit,
    OverDailyLimit,
    InsufficientBalance,
    NotEnoughGas,
    WithdrawalPending,
    NoPendingWithdrawal,
    WithdrawalNotReady,
    ZeroAmount,
    BadConfig,
    BadSignature,
    MalformedVerdict,
    VerdictRefused,
    VerdictMismatch,
    AudioReused,
    BadEnrollmentDigest,
}

impl AsRef<str> for VaultError {
    fn as_ref(&self) -> &str {
        match self {
            Self::AccountNotSpeakable => "account is not speakable",
            Self::AlreadyExists => "vault already exists",
            Self::NoVault => "no vault for this account",
            Self::InsufficientDeposit => "deposit below the storage reserve",
            Self::ZeroDeposit => "attach a deposit",
            Self::ContactExists => "contact already saved",
            Self::BadContact => "the owner or the vault cannot be a contact",
            Self::ContactNotFound => "contact not found",
            Self::TooManyContacts => "contact list is full",
            Self::SoundsLikeContact => "account sounds like a saved contact",
            Self::InvalidLimits => "limits need 0 < per_transfer <= daily",
            Self::NoLimitsChange => "no limits change is pending",
            Self::BadNonce => "nonce is not the next nonce",
            Self::BadReceiver => "the owner or the vault cannot receive a transfer",
            Self::AmountNotSpeakable => "amount is not speakable",
            Self::OverTransferLimit => "amount is above the transfer limit",
            Self::OverDailyLimit => "amount is above the daily limit",
            Self::InsufficientBalance => "amount is above the free balance",
            Self::NotEnoughGas => "attach more gas",
            Self::WithdrawalPending => "a withdrawal is pending",
            Self::NoPendingWithdrawal => "no withdrawal is pending",
            Self::WithdrawalNotReady => "withdrawal delay has not passed",
            Self::ZeroAmount => "amount must be above zero",
            Self::BadConfig => "invalid verifier configuration",
            Self::BadSignature => "verdict signature does not verify against the pinned key",
            Self::MalformedVerdict => "verdict is not a seams_voice_signed_verdict_v1",
            Self::VerdictRefused => "the verifier refused",
            Self::VerdictMismatch => "verdict is for another request",
            Self::AudioReused => "audio digest was used before",
            Self::BadEnrollmentDigest => "enrollment digest is not base64url of 32 bytes",
        }
    }
}
